    /** 冻结历史夹具或纯契约回归，不通过旧业务路径生成运行。 */
    public static function check(string $body, bool $met = true): array
    {
        $quote = function (string $text) use ($body): array {
            foreach (explode("\n", $body) as $index => $paragraph) {
                if (str_contains($paragraph, $text)) {
                    return [['paragraph' => $index + 1, 'quote' => $text]];
                }
            }
            throw new \RuntimeException('夹具缺少预期引文');
        };

        return ['points' => [['id' => 'chapter-1-point-1', 'met' => $met, 'reason' => '隔离验证行动及变化', 'evidence' => $met ? $quote('她的心跳加速，确认了来信的真实性') : []]],
            'hook' => ['met' => $met, 'reason' => '隔离检查神秘访客触发', 'evidence' => $met ? $quote('师父的秘密，比你想象的更危险。') : []], 'conflicts' => []];
    }

    /** 冻结历史夹具或纯契约回归，不通过旧业务路径生成运行。 */
    public function test_real_source_anchor_manifest_excludes_empty_lines(): void
    {
        $this->assertSame(2059, ContentSchema::count(self::sourceBody()));
        $this->assertCount(33, ContentSchema::paragraphs(self::sourceBody()));
        $anchors = ContentSchema::anchors(self::sourceBody());
        $this->assertCount(22, $anchors);
        foreach ([2, 6, 28] as $number) {
            $this->assertArrayNotHasKey('p'.$number, $anchors);
        }
        $this->assertSame(31, $anchors['p31']['paragraph']);
    }
