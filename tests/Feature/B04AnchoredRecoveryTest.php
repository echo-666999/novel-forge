    public static function patches(): array
    {
        return ['insertions' => array_map(fn ($id, $seed) => ['anchor_id' => $id, 'text' => str_repeat($seed, 100), 'reason' => '隔离段落预算'], ['p1', 'p3', 'p4'], ['甲行动', '乙比对', '丙记录'])];
